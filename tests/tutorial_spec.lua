local addonName, ns = ...
local A = ns.Assert
local function host(options) return ns.host(options) end
local function snapshot(h) return h.ns.Assign.Snapshot() end

A.test("first login starts the tour once (3 s after world entry); the flag persists so it never repeats", function()
    local h = host(); h.login(); h.event("PLAYER_ENTERING_WORLD")
    A.equal(h.ns.Tutorial.running, false); h.runTimers()
    A.equal(h.ns.Tutorial.running, true); A.equal(h.ns.Tutorial.step, 1)
    A.equal(h.ns.db.global.tutorial.seen, true)
    A.equal(h.named("StreonorDockTutorial"):IsShown(), true)
    -- same account, next login / update: seen survives, no tour
    local h2 = host({db = h.env.StreonorDockDB, saved = h.env.StreonorDockCharDB}); h2.login(); h2.event("PLAYER_ENTERING_WORLD"); h2.runTimers()
    A.equal(h2.ns.Tutorial.running, false)
end)
A.test("Next walks seven steps without touching assignments; the last one completes without hiding popups", function()
    local h = host(); h.login(); h.event("PLAYER_ENTERING_WORLD"); h.runTimers()
    local before = snapshot(h)
    local callout = h.named("StreonorDockTutorial")
    for step = 1, 7 do
        A.equal(h.ns.Tutorial.step, step); A.equal(callout.progress.text, step .. "/7")
        if step < 7 then h.fire(callout.next, "OnClick") end
    end
    A.equal(callout.next.text, "Done")
    h.fire(callout.next, "OnClick")
    A.equal(h.ns.Tutorial.running, false); A.equal(callout:IsShown(), false)
    A.equal(h.ns.db.global.tutorial.completed, true); A.equal(h.ns.db.global.tutorial.hidePopups, false)
    A.equal(snapshot(h), before); A.equal(h.ns.Assign.IsActive(), false); A.equal(#h.popups, 0); A.equal(h.reloaded, nil)
end)
A.test("X closes all remaining tips and sets the account-wide hide flag; never auto-resumes", function()
    local h = host(); h.login(); h.event("PLAYER_ENTERING_WORLD"); h.runTimers()
    local callout = h.named("StreonorDockTutorial")
    h.fire(callout.next, "OnClick")
    h.fire(callout.close, "OnClick")
    A.equal(h.ns.Tutorial.running, false); A.equal(h.ns.db.global.tutorial.hidePopups, true); A.equal(callout:IsShown(), false)
    local h2 = host({db = h.env.StreonorDockDB, saved = h.env.StreonorDockCharDB}); h2.login()
    h2.ns.db.global.tutorial.seen = false          -- even if seen were lost, hidePopups blocks the automatic tour
    h2.event("PLAYER_ENTERING_WORLD"); h2.runTimers(); A.equal(h2.ns.Tutorial.running, false)
end)
A.test("Escape acts like X", function()
    local h = host(); h.login(); h.event("PLAYER_ENTERING_WORLD"); h.runTimers()
    local callout = h.named("StreonorDockTutorial")
    A.equal(h.env.UISpecialFrames[#h.env.UISpecialFrames], "StreonorDockTutorial")
    callout:Hide()
    A.equal(h.ns.Tutorial.running, false); A.equal(h.ns.db.global.tutorial.hidePopups, true)
end)
A.test("replay from settings works after X; the hide flag can be cleared by the user only", function()
    local h = host(); h.login(); h.event("PLAYER_ENTERING_WORLD"); h.runTimers()
    h.fire(h.named("StreonorDockTutorial").close, "OnClick")
    local general = h.ns.Options.Build().args.general.args
    general.tutorial.func(); A.equal(h.ns.Tutorial.running, true); A.equal(h.ns.Tutorial.step, 1)
    A.equal(h.ns.db.global.tutorial.hidePopups, true, "replay does not reset the flag by itself")
    h.fire(h.named("StreonorDockTutorial").close, "OnClick")
    general.hidetips.set(nil, false); A.equal(h.ns.db.global.tutorial.hidePopups, false)
end)
A.test("combat suspends before any frame work and resumes on the same step", function()
    local h = host(); h.login(); h.event("PLAYER_ENTERING_WORLD"); h.runTimers()
    local callout = h.named("StreonorDockTutorial")
    h.fire(callout.next, "OnClick"); h.fire(callout.next, "OnClick")
    h.combat = true; h.event("PLAYER_REGEN_DISABLED")
    A.equal(callout:IsShown(), false); A.equal(h.ns.Tutorial.step, 3); A.equal(h.ns.Tutorial.running, true)
    A.equal(h.ns.db.global.tutorial.hidePopups, false, "hiding for combat is not a dismissal")
    h.combat = false; h.event("PLAYER_REGEN_ENABLED")
    A.equal(callout:IsShown(), true); A.equal(h.ns.Tutorial.step, 3); A.equal(h.blocked, 0)
end)
A.test("hidden bar and minimap fall back to a centred callout; step 5 uses an inert example popup", function()
    local h = host(); h.login(); h.ns.profile.general.showActionBar = false; h.ns.Bar.Layout()
    h.ns.Tutorial.Replay()
    local callout = h.named("StreonorDockTutorial")
    A.equal(callout.text.text:find("centre of the screen") ~= nil, true)
    for _ = 1, 5 do h.fire(callout.next, "OnClick") end
    A.equal(h.ns.Tutorial.step, 6)
    local example = h.named("StreonorDockTutorialExample"); A.equal(example:IsShown(), true)
    A.equal(#h.popups, 0); A.equal(h.reloaded, nil)
    h.fire(callout.next, "OnClick"); A.equal(example:IsShown(), false)
    A.equal(callout.text.text:find("centre of the screen") ~= nil, true, "no minimap button in the host")
end)
A.test("the tour holds a visibility override and releases it exactly once", function()
    local h = host(); h.login()
    local v = h.ns.Visibility
    h.ns.Tutorial.Replay(); A.equal(v.override, 1)
    h.fire(h.named("StreonorDockTutorial").close, "OnClick"); A.equal(v.override, 0)
    h.ns.Tutorial.Replay(); h.ns.Tutorial.Finish(); h.ns.Tutorial.Finish(); A.equal(v.override, 0)
end)
