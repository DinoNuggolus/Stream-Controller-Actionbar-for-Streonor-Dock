A.test("mismatch overrides the group; verified disagreement splits the item",function()
    local g, ig=data()
    local store={}
    local t=tracker(store,g,ig)
    t:press(8,100,1); t:observe(8,100,60,100.5)
    A.equal(store.groups.heal.duration,60); A.equal(store.groups.heal.verified,true)
    A.equal(t.log[1].kind,"mismatch"); A.equal(t.log[1].table,120); A.equal(t.log[1].game,60)
    A.equal(t:pressDuration(9),60,"override applies to other members")
    t:press(9,300,1); t:observe(9,300,90,300.2)
    A.equal(store.items[9].duration,90); A.equal(store.groups.heal.duration,60)
    A.equal(t.log[2].kind,"conflict")
    A.equal(t:pressDuration(9),90); A.equal(select(2,t:pressDuration(9)),"item")
    A.equal(t:pressDuration(8),60)
    t:press(9,500,1); t:observe(9,500,90,500.1); A.equal(#t.log,2,"split item confirming itself is quiet")
    t:press(30,600,1); A.equal(t:running(30,600),false)
    t:press(30,600,1,nil,false); t:observe(30,600,30,600.5)
    A.equal(store.groups.bandage.duration,30); A.equal(t.log[3].table,0)
    A.equal(t:press(30,700,1),true)
end)
