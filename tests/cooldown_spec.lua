local addonName, ns = ...
local A = ns.Assert
local chunk = loadfile("src/StreonorDock/Cooldown.lua")
if chunk then chunk(addonName, ns) end
local function tracker()
    A.equal(type(ns.CooldownTracker),"table","CooldownTracker module available")
    return ns.CooldownTracker.new()
end
local function remaining(t,id,now,seconds,source)
    local actual, tag=t:remaining(id,now); A.equal(actual,seconds); A.equal(tag,source)
end
A.test("readable cooldown learns duration and labels game source",function()
    local t=tracker()
    remaining(t,8,100,0,nil)
    A.equal(t:observe(8,100,30,105),true)
    remaining(t,8,105,25,"game"); remaining(t,8,130,0,nil)
    A.equal(t:useDetected(8,140),true)
    remaining(t,8,145,25,"est"); remaining(t,8,170,0,nil)
end)
A.test("GCD samples do not teach overwrite or clear an active timer",function()
    local t=tracker()
    t:observe(8,100,30,100)
    A.equal(t:observe(8,110,1.5,110),false)
    A.equal(t:observe(8,110,1,110),false)
    remaining(t,8,110,20,"game")
    t:observe(9,100,1.5,100); t:useDetected(9,100)
    remaining(t,9,101,nil,"est")
end)
A.test("unavailable samples preserve timer and unknown use learns later",function()
    local t=tracker()
    t:useDetected(8,100); remaining(t,8,101,nil,"est")
    A.equal(t:useDetected(8,102),false)
    t:observe(8,nil,nil,103); remaining(t,8,103,nil,"est")
    t:observe(8,100,20,105); remaining(t,8,105,15,"game")
    t:observe(8,nil,nil,106); remaining(t,8,106,14,"game")
    t:observe(8,0,0,107); remaining(t,8,107,0,nil)
    t:useDetected(8,110); remaining(t,8,111,19,"est")
end)
A.test("duplicate detections cannot extend active estimates or game timers",function()
    local t=tracker()
    t:observe(8,100,20,100)
    A.equal(t:useDetected(8,102),false); remaining(t,8,103,17,"game")
    t:useDetected(8,121)
    A.equal(t:useDetected(8,122),false); remaining(t,8,125,16,"est")
end)
A.test("item change and clear remove timer and learning without cross item leakage",function()
    local t=tracker()
    t:observe(8,100,20,100); t:observe(9,100,50,100)
    t:changeItem(8,8); remaining(t,8,105,15,"game")
    t:changeItem(8,9); remaining(t,8,105,0,nil); remaining(t,9,105,45,"game")
    t:useDetected(8,106); remaining(t,8,107,nil,"est")
    t:clear(9); t:useDetected(9,110); remaining(t,9,111,nil,"est")
end)
A.test("invalid samples cannot poison learned cooldowns",function()
    local t=tracker()
    t:observe(8,100,20,100)
    for _, sample in ipairs({{8,-1,20,100},{8,100,-1,100},{8,100,math.huge,100},
        {8,100,0/0,100},{8,"100",20,100},{0,100,20,100},{8,101,20,100},
        {8,100,20,"bad"},{8,100,20,-1}}) do
        A.equal(t:observe(unpack(sample)),false)
    end
    remaining(t,8,105,15,"game")
    A.equal(t:useDetected(0,105),false); A.equal(t:useDetected(8,"bad"),false)
    remaining(t,8,"bad",nil,nil)
end)
