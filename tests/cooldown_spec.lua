A.test("sharing evidence: same start shared; ready member is not-shared evidence",function()
    local g, ig=data()
    local store={}
    local t=tracker(store,g,ig)
    t:press(8,100,1); t:observe(8,100,120,100.5)
    t:observe(10,100.3,120,101)
    A.equal(store.pools.potion.sharedVerified,true); A.equal(t.log[#t.log].kind,"shared")
    remaining(t,8,110,110,"game")
    local s2={}
    local t2=tracker(s2,g,ig)
    t2:press(8,100,1); t2:observe(8,100,120,100.5)
    t2:observe(10,0,0,101)
    A.equal(s2.pools.potion.notShared,true); A.equal(t2.log[#t2.log].kind,"not-shared")
    remaining(t2,8,101,119,"game")   -- another member's ready state does not clear the lock
end)
A.test("build change keeps data but marks it unverified",function()
    local store={build="70790",items={[99]={duration=30,verified=true},[0]={duration=5}},
        groups={heal={duration=60,verified=true,itemsSeen={8,"x"}},bad={duration=-1}},
        pools={potion={sharedVerified=true}}}
    local g, ig=data()
    local t=tracker(store,g,ig,{build="70800"})
    A.equal(store.build,"70800"); A.equal(store.items[99].verified,nil); A.equal(store.items[0],nil)
    A.deep(store.groups.heal,{duration=60,itemsSeen={8}}); A.equal(store.groups.bad,nil)
    A.equal(store.pools.potion.sharedVerified,nil)
    A.equal(t:pressDuration(9),60,"unverified data still beats the shipped table")
    t:press(9,100,1); t:observe(9,100,120,100.5)
    A.equal(store.groups.heal.duration,120); A.equal(store.groups.heal.verified,true); A.equal(store.items[9],nil)
    local same={build="70800",groups={heal={duration=60,verified=true}}}
    tracker(same,g,ig,{build="70800"}); A.equal(same.groups.heal.verified,true)
end)
A.test("precedence: live game > item override > group > table > base > used",function()
    local g, ig=data()
    local store={items={[9]={duration=45}},groups={heal={duration=70}}}
    local t=tracker(store,g,ig)
    A.equal(t:pressDuration(9,10),45); A.equal(t:pressDuration(8,10),70)
    A.equal(t:pressDuration(10,10),120); A.equal(t:pressDuration(99,10),10); A.equal(t:pressDuration(99),nil)
    t:press(9,100,1); remaining(t,9,100,45,"est")
    t:observe(9,99,200,101); remaining(t,9,101,198,"game")
    t:observe(9,0,0,400); remaining(t,9,400,0,nil)
end)
A.test("readable game data reconciles estimates; grace; GCD and invalid samples ignored",function()
    local t=tracker({},{},{})
    t:press(8,100,1,60)
    A.equal(t:observe(8,0,0,100.5),false,"pre-ack ready sample within grace")
    remaining(t,8,101,59,"est")
    A.equal(t:observe(8,0,0,105),true,"failed use self-corrects"); remaining(t,8,105,0,nil)
    t:observe(8,100,20,100)
    A.equal(t:observe(8,110,1.5,110),false)
    for _, sample in ipairs({{8,-1,20,100},{8,100,-1,100},{8,100,math.huge,100},{8,100,0/0,100},
        {8,"100",20,100},{0,100,20,100},{8,111,20,110},{8,100,20,"bad"},{8,nil,nil,110}}) do
        A.equal(t:observe(unpack(sample)),false)
    end
    remaining(t,8,110,10,"game")
    local secret={}
    local s=tracker({},{},{},{issecret=function(v) return rawequal(v,secret) end})
    A.equal(s:observe(8,secret,secret,100),false,"injected predicate rejects sealed readings")
    remaining(t,8,"bad",nil,nil); A.equal(t:timer(8,"bad"),nil)
end)
