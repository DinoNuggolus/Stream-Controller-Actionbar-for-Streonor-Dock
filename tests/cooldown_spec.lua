A.test("nil duration is unknown: used with elapsed, then learned from own use",function()
    local g, ig=data()
    local t=tracker({},g,ig)
    t:press(40,100,1); remaining(t,40,150,nil,"used")
    local _,_,source,usedAt=t:timer(40,150); A.equal(source,"used"); A.equal(usedAt,100)
    t:press(99,100,1,45); remaining(t,99,100,45,"est")
    t:press(98,100,1,1.0); remaining(t,98,100,nil,"used")
    remaining(t,40,100+3600,0,nil)
    t:observe(40,3800,180,3801)
    A.equal(t:learnedDuration(40),nil,"not our press: no learning")
    t:press(40,4000,1); t:observe(40,4000.3,180,4001)
    A.equal(t:learnedDuration(40),180)
end)
