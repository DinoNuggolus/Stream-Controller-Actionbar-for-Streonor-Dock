local addonName, ns = ...
local A = ns.Assert
local chunk = loadfile("src/StreonorDock/Cooldown.lua")
if chunk then chunk(addonName, ns) end
local function tracker(store, groups, itemGroups, options)
    A.equal(type(ns.CooldownTracker),"table","CooldownTracker module available")
    return ns.CooldownTracker.new(store, groups, itemGroups, options)
end
local function remaining(t,id,now,seconds,source)
    local actual, tag=t:remaining(id,now); A.equal(actual,seconds); A.equal(tag,source)
end
-- Small synthetic table (not the shipped data): three groups in pool "potion", unlabelled
-- groups, a dormant group and an unknown-duration group.
local function data()
    return {heal={name="Heal",duration=120,shared="potion"},mana={name="Mana",duration=120,shared="potion"},
        prot={name="Prot",duration=90,shared="potion"},
        juju={name="Juju",duration=60,shared=nil},juju2={name="Juju2",duration=60},
        bandage={name="Bandage",duration=0},troll={name="Troll",duration=nil},
        bad={duration=-3,shared=true}},
        {[8]="heal",[9]="heal",[10]="mana",[11]="prot",[20]="juju",[21]="juju2",[22]="juju",
         [30]="bandage",[40]="troll",[50]="missing",[0]="heal"}
end
A.test("shipped reference data loads with pool labels, unverified, without BOM",function()
    local f=io.open("src/StreonorDock/CooldownData.lua","rb"); local head=f:read(3); f:close()
    A.equal(head~="\239\187\191",true,"no UTF-8 BOM")
    local env={}; loadfile("src/StreonorDock/CooldownData.lua")("StreonorDock",env)
    A.equal(env.CooldownGroups.health_potion.shared,"potion"); A.equal(env.ItemGroups[118],"health_potion")
    for key, g in pairs(env.CooldownGroups) do
        A.equal(g.verified,false,key .. " ships unverified"); A.equal(type(g.source),"string")
    end
    for _, key in pairs(env.ItemGroups) do A.equal(type(env.CooldownGroups[key]),"table",key) end
    local t=tracker({},env.CooldownGroups,env.ItemGroups)
    A.equal(t:key(118),"pool:potion"); A.equal(t:key(13444),"pool:potion"); A.equal(t:key(12450),"group:juju_flurry")
    A.equal(select(2,t:pressDuration(14530)),"dormant")
end)
A.test("group lookup validates data and keys timers by pool label or group",function()
    local g, ig=data()
    local t=tracker({},g,ig)
    A.equal(t:group(8),"heal"); A.equal(t:group(50),nil); A.equal(t:group(0),nil)
    A.equal(t:key(8),"pool:potion"); A.equal(t:key(10),"pool:potion"); A.equal(t:key(20),"group:juju")
    A.equal(t:key(21),"group:juju2"); A.equal(t:key(99),99)
    A.equal(t.groups.bad.shared,nil); A.equal(t.groups.bad.duration,nil)
    A.deep(t:poolMembers(8),{9,10,11}); A.deep(t:poolMembers(20),{22}); A.deep(t:poolMembers(99),{})
    A.equal(type(tracker(false,false,"x").groups),"table")
    A.equal(g.bad.duration,-3,"input not mutated")
end)
A.test("press guards: id, plain positive count, not running, dormant, setting",function()
    local g, ig=data()
    local t=tracker({},g,ig)
    A.equal(select(2,t:press(0,100,1)),"invalid"); A.equal(select(2,t:press(8,"x",1)),"invalid")
    for _, count in ipairs({0,-1,"3",false,0/0}) do A.equal(select(2,t:press(8,100,count)),"count") end
    A.equal(select(2,t:press(8,100,nil)),"count")
